#!/usr/bin/env python3
"""Author original, solvable puzzles by reverse pulls; simplify using push A*."""
from collections import deque
from heapq import heappush, heappop
from itertools import permutations
from pathlib import Path
import random
W,H=11,9
LEVELS_PER_PACK=20
D=[(-W,'U'),(1,'R'),(W,'D'),(-1,'L')]
def reach(walls,boxes,start):
    paths={start:''}; q=deque([start])
    while q:
        p=q.popleft()
        for d,c in D:
            n=p+d
            if 0<=n<W*H and n not in walls and n not in boxes and n not in paths:
                paths[n]=paths[p]+c;q.append(n)
    return paths

def solve(walls,goals,boxes,player):
    targets=tuple(sorted(goals)); cache={}
    def heuristic(bs):
        if bs not in cache:
            cache[bs]=min(sum(abs(b%W-g%W)+abs(b//W-g//W) for b,g in zip(bs,perm)) for perm in permutations(targets))
        return cache[bs]*1000
    bs=tuple(sorted(boxes)); paths=reach(walls,set(bs),player); key=(bs,min(paths))
    queue=[]; heappush(queue,(heuristic(bs),0,bs,player,'')); best={key:0}
    visits=0
    while queue and visits<60000:
        _,cost,bs,p,route=heappop(queue); visits+=1
        if set(bs)==goals:return route
        paths=reach(walls,set(bs),p);key=(bs,min(paths))
        if best.get(key)!=cost:continue
        for b in bs:
            for d,c in D:
                behind=b-d;n=b+d
                if behind not in paths or n in walls or n in bs:continue
                if n not in goals and ((n-1 in walls or n+1 in walls) and (n-W in walls or n+W in walls)):continue
                nxt=set(bs);nxt.remove(b);nxt.add(n);nbs=tuple(sorted(nxt))
                nr=reach(walls,nxt,b);nk=(nbs,min(nr));nc=cost+1000+len(paths[behind])+1
                if nc<best.get(nk,10**9):
                    best[nk]=nc;heappush(queue,(nc+heuristic(nbs),nc,nbs,b,route+paths[behind]+c))
    return None

def create(difficulty,index):
    for attempt in range(100):
        rng=random.Random(7331+difficulty*999+index*101+attempt*17)
        walls={i for i in range(W*H) if i%W in (0,W-1) or i//W in (0,H-1)}
        for x,y in [(4,2),(6,6),(2,4),(8,4),(5,4),(4,6),(6,2)][:2+difficulty]:walls.add(y*W+x)
        if index >= 4:
            patterns=[[(3,3),(4,3),(7,5)],[(3,5),(4,5),(7,3)],
                      [(5,2),(5,3),(5,5),(5,6)],[(3,2),(3,3),(7,5),(7,6)],
                      [(3,4),(4,4),(6,4),(7,4)],[(3,3),(7,3),(3,5),(7,5)]]
            for x,y in patterns[(index-4)%len(patterns)]:walls.add(y*W+x)
        free=[y*W+x for y in range(2,H-2) for x in range(2,W-2) if y*W+x not in walls]
        goals=set(rng.sample(free,difficulty+1));boxes=set(goals);player=rng.choice([p for p in free if p not in boxes]);reverse=''
        previous=None
        for _ in range(12+difficulty*7+index*3):
            paths=reach(walls,boxes,player);choices=[]
            for b in boxes:
                for d,c in D:
                    stand=b+d;retreat=b+2*d
                    if stand in paths and 0<=retreat<W*H and retreat not in walls and retreat not in boxes:
                        if previous!=(b,-d):choices.append((b,d,c,paths[stand]))
            if not choices:break
            b,d,c,path=rng.choice(choices);reverse+=path+c
            boxes.remove(b);boxes.add(b+d);player=b+2*d;previous=(b+d,d)
        if boxes==goals:continue
        route=solve(walls,goals,boxes,player)
        if not route or len(route)<5+difficulty*5+(index//4*2 if index>=4 else 0):continue
        p=player;bs=set(boxes);pushes=0
        for c in route:
            d=dict((c,d) for d,c in D)[c];n=p+d
            assert n not in walls
            if n in bs:
                assert n+d not in walls and n+d not in bs
                bs.remove(n);bs.add(n+d);pushes+=1
            p=n
        assert bs==goals
        lines=[]
        for y in range(H):
            line=''
            for x in range(W):
                p=y*W+x
                line+= '#' if p in walls else '+' if p==player and p in goals else '@' if p==player else '*' if p in boxes and p in goals else '$' if p in boxes else '.' if p in goals else ' '
            lines.append(line)
        return lines,route,pushes
    raise RuntimeError('No suitable puzzle')
if __name__=='__main__':
    puzzles=[create(d,i) for d in range(4) for i in range(LEVELS_PER_PACK)]
    output=['#pragma once','#include <cstdint>','namespace arcade::sokoban {',
            'struct Puzzle { const char *map; const char *solution; uint16_t moves, pushes; };',
            '// Original maps generated by tools/generate_sokoban_levels.py; witnesses tested natively.',
            'inline constexpr Puzzle Puzzles[] = {']
    for i,(lines,route,pushes) in enumerate(puzzles):
        output.append('    { // Pack %d, phase %d'%(i//LEVELS_PER_PACK+1,i%LEVELS_PER_PACK+1))
        output.extend('        "'+line+'"' for line in lines)
        output.append('        , "'+route+'", '+str(len(route))+', '+str(pushes)+'},')
    output.extend(['};','}'])
    target=Path(__file__).resolve().parents[1]/'main/games/sokoban/levels.h'
    target.write_text('\n'.join(output)+'\n')
    print('Created '+str(len(puzzles))+' original verified puzzles:',[(len(r),p) for _,r,p in puzzles])
